// Referenced so variants used only by another platform's shortcut tables stay live on every
// target, and so `ALL` — consumed by tests alone — is used by plain builds too.
const _: usize = Label::ALL.len();

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_label_resolves_in_every_locale() {
        for label in Label::ALL {
            for locale in Locale::ALL {
                assert!(
                    !label.t(*locale).is_empty(),
                    "{label:?} is empty in {locale:?}"
                );
            }
        }
    }

    #[test]
    fn invariant_labels_hold_in_every_locale() {
        for locale in Locale::ALL {
            // The compact sidebar centers a bare "+", so the expanded footer keeps the prefix.
            assert!(Label::NewSpace.t(*locale).starts_with('+'));
            assert_eq!(Label::ProductName.t(*locale), "Vivida");
        }
    }
}
