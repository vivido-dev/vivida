//! Localized chrome labels: one [`Label`] per user-visible string.

// Rust guideline compliant 2026-10-07

use crate::locale::Locale;

/// A user-visible chrome string.
///
/// Each variant resolves through [`Label::t`]. The per-locale matches are exhaustive, so adding
